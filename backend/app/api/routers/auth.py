@router.post("/send-otp")
async def send_otp(request: dict, db: Session = Depends(get_db)):
    """Store OTP for user (called by Admin before test)"""
    email = request.get("email")
    otp_code = request.get("otp")
    
    if not email:
        raise HTTPException(status_code=400, detail="Email is required")
    
    if not otp_code:
        raise HTTPException(status_code=400, detail="OTP is required")
    
    # Check if user exists, if not create them
    user = db.query(User).filter(User.email == email).first()
    
    if not user:
        # Create user with placeholder name
        new_user = User(
            name=email.split('@')[0],
            email=email,
            created_at=datetime.now().isoformat()
        )
        db.add(new_user)
        db.commit()
    
    # Save OTP to database
    save_candidate_otp(email.split('@')[0], email, otp_code, db)
    
    return {
        "status": "success",
        "message": f"OTP stored for {email}"
    }

