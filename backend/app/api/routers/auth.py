@router.post("/auth/candidate-login")
async def candidate_login(body: dict, db: Session = Depends(get_db)):
    """Candidate login — verified against SQLite auth_users table (role=candidate)."""
    email = (body.get("email") or "").strip().lower()
    password = (body.get("password") or "").strip()

    if not email or not password:
        raise HTTPException(status_code=400, detail="Email and password are required.")

    user = authenticate_user(db, email, password)
    if not user:
        raise HTTPException(status_code=401, detail="Invalid email or password.")
    if user["role"] != "candidate":
        raise HTTPException(status_code=403, detail="Not a candidate account.")

    return {
        "status": "success",
        "role": user["role"],
        "email": user["email"],
        "name": user["name"],
        "user_id": user["id"],
    }


